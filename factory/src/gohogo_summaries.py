# 要約の目安。40字前後の一文にそろえる(短すぎると内容が伝わらず、
# 長すぎると一覧に並べたとき読みにくい)。
MIN_SUMMARY_CHARS = 25
MAX_SUMMARY_CHARS = 50

# サイト掲載の要約と「近すぎる」と見なす閾値。
# 同じ本文の要旨である以上ある程度は似るが、これを超えたら書き直す。
SIMILARITY_LIMIT = 0.6


def get_summary(hen, chapter, title=None):
    """その章の要約。titleを渡すと、章題が一致した場合だけ返す
    (一致しなければNone。章の取り違えを黙って通さないため)。"""
    entry = SUMMARIES.get((hen, chapter))
    if entry is None:
        return None
    expected_title, summary = entry
    if title is not None and title != expected_title:
        return None
    return summary


def expected_title(hen, chapter):
    """要約を書いたときの章題(照合に失敗した理由を示すため)"""
    entry = SUMMARIES.get((hen, chapter))
    return entry[0] if entry else None


def _bigrams(text):
    return {text[i:i + 2] for i in range(len(text) - 1)}


def bigram_dice(a, b):
    """2文字組の重なり具合(0〜1)。語順を変えただけの言い換えを捕まえる"""
    ga, gb = _bigrams(a), _bigrams(b)
    if not ga or not gb:
        return 1.0 if a == b else 0.0
    return 2 * len(ga & gb) / (len(ga) + len(gb))


def sequence_ratio(a, b):
    """並びを見た類似度(0〜1)。言い回しをなぞっている場合に高くなる"""
    return difflib.SequenceMatcher(None, a, b).ratio()


def similarity(a, b):
    """2つの見方のうち高いほうを採る(どちらか一方でも似ていれば近いと見なす)"""
    return max(bigram_dice(a, b), sequence_ratio(a, b))


def similarity_report(summary, site_summary):
    """自前の要約とサイト掲載の要約を比べ、(近すぎるか, 値, 内訳)を返す"""
    if not site_summary:
        return False, 0.0, {"dice": 0.0, "ratio": 0.0}
    if summary == site_summary:
        return True, 1.0, {"dice": 1.0, "ratio": 1.0}
    dice = bigram_dice(summary, site_summary)
    ratio = sequence_ratio(summary, site_summary)
    score = max(dice, ratio)
    return score >= SIMILARITY_LIMIT, score, {"dice": dice, "ratio": ratio}
